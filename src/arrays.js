// 1.Выведите в консоль сумму всех элементов массива.

// Вычисляем сумму всех элементов массива
let sum = 0;

for (let i = 0; i < numbers.length; i++) {
    sum += numbers[i];
}

// Выводим результат
console.log("Массив: " + numbers);
console.log("Сумма всех элементов: " + sum);


