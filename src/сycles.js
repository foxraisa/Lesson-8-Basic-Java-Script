// 3.Запросить у пользователя ввод числа N. Вывести в консоль среднее арифметическое всех нечётных чисел от 1 до N

// Запросить у пользователя ввод числа N
let userInput = prompt("Введите число N:");

// Проверяем, что пользователь ввел данные
if (userInput !== null) {
    // Преобразуем введенную строку в число
    let N = parseInt(userInput);
    
    // Проверяем, что введено корректное число
    if (!isNaN(N) && N >= 1) {
        
        let sum = 0;    // Сумма нечетных чисел
        let count = 0;  // Количество нечетных чисел
        
        // Проходим по всем числам от 1 до N
        for (let i = 1; i <= N; i++) {
            // Проверяем, является ли число нечетным
            if (i % 2 !== 0) {
                sum += i;    // Добавляем число к сумме
                count++;     // Увеличиваем счетчик
            }
        }
        
        // Вычисляем среднее арифметическое
        let average = sum / count;
        
        // Выводим результат
        console.log("Среднее арифметическое нечетных чисел от 1 до " + N + ": " + average.toFixed(2));
        
    } else {
        console.log("Ошибка: пожалуйста, введите целое число больше или равное 1!");
    }
} else {
    console.log("Ввод отменен пользователем.");
}